//! `twin sim-pack`: compile the engine to WebAssembly and pack it (plus the example scenarios)
//! as scripts for the viewer. `twin sim <scenario.geojson>`: evaluate a scenario natively.

use crate::aoi::root;
use crate::http::Res;
use base64::Engine as _;
use serde_json::Value;

pub fn pack() -> Res<()> {
    let twin = root().join("twin");
    println!("  compiling the engine to WebAssembly");
    let st = std::process::Command::new("cargo")
        .args(["build", "-p", "sim-wasm", "--release", "--target", "wasm32-unknown-unknown"])
        .current_dir(&twin)
        .status()
        .map_err(|e| format!("could not run cargo ({e}); is ~/.cargo/bin on PATH?"))?;
    if !st.success() {
        return Err("wasm build failed (run `rustup target add wasm32-unknown-unknown` once)".into());
    }
    let wasm = std::fs::read(twin.join("target/wasm32-unknown-unknown/release/sim_wasm.wasm"))?;
    let b64 = base64::engine::general_purpose::STANDARD.encode(&wasm);
    let js = format!("/* Generated by `twin sim-pack` from twin/sim (Rust). Do not edit by hand. */\nwindow.SIM_WASM = \"{b64}\";\n");
    let out = root().join("campus/js/sim-wasm.js");
    std::fs::write(&out, js)?;
    println!("  {} ({:.0} KB wasm)", out.display(), wasm.len() as f64 / 1024.0);
    // Example scenarios.
    let mut ex = Vec::new();
    let dir = root().join("scenarios");
    if let Ok(rd) = std::fs::read_dir(&dir) {
        let mut files: Vec<_> = rd.flatten().map(|e| e.path()).filter(|p| p.extension().map_or(false, |x| x == "geojson")).collect();
        files.sort();
        for f in files {
            let text = std::fs::read_to_string(&f)?;
            let v: Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", f.display()))?;
            ex.push(serde_json::json!({ "file": f.file_name().unwrap().to_string_lossy(), "plan": v }));
        }
    }
    let n = ex.len();
    let js = format!("/* Generated by `twin sim-pack` from scenarios/*.geojson. */\nwindow.SANDBOX_EXAMPLES = {};\n", Value::Array(ex));
    std::fs::write(root().join("campus/data/scenarios.js"), js)?;
    println!("  packed {n} example scenarios");
    Ok(())
}

fn load_world() -> Res<sim::World> {
    let text = std::fs::read_to_string(root().join("campus/data/campus-data.js"))?;
    Ok(sim::World::load(&text)?)
}

fn pct(v: &Value) -> String {
    format!("{:.0}%", v.as_f64().unwrap_or(0.0) * 100.0)
}

fn inr(x: f64) -> String {
    if x >= 1e7 {
        format!("₹{:.2} crore", x / 1e7)
    } else if x >= 1e5 {
        format!("₹{:.2} lakh", x / 1e5)
    } else {
        format!("₹{:.0}", x)
    }
}

pub fn run(file: &str, as_json: bool) -> Res<()> {
    let w = load_world()?;
    let text = std::fs::read_to_string(file)?;
    let sc = sim::parse(&text, &w.frame)?;
    let title = sc.meta.get("title").and_then(|t| t.as_str()).unwrap_or(file).to_string();
    let ctx = sim::prepare(&w, sc);
    let r = sim::evaluate(&w, &ctx);
    if as_json {
        println!("{}", serde_json::to_string_pretty(&r)?);
        return Ok(());
    }
    let b = &r["budget"];
    println!("## {title}\n");
    println!("| | Today | With the plan |\n|---|---|---|");
    let wf = &r["wifi"];
    if wf["plan"]["aps"].as_u64().unwrap_or(0) + wf["base"]["aps"].as_u64().unwrap_or(0) > 0 {
        println!("| Wi-Fi: floor area with good signal (-67 dBm) in {} measured buildings | {} | {} |", wf["targets"].as_array().map_or(0, |a| a.len()), pct(&wf["base"]["good"]), pct(&wf["plan"]["good"]));
    }
    let l = &r["light"];
    if l["study_m"].as_f64().unwrap_or(0.0) > 0.0 {
        println!("| Lit road meeting IS 1944 (m of {} m studied) | {} | {} |", l["study_m"], l["base"]["ok_m"], l["plan"]["ok_m"]);
    }
    for a in r["access"].as_array().into_iter().flatten() {
        println!("| People within {:.0} m walk of a {} | {} | {} |", a["radius"].as_f64().unwrap_or(0.0), a["label"].as_str().unwrap_or("").to_lowercase(), pct(&a["base"]["pct"]), pct(&a["plan"]["pct"]));
    }
    println!("\n**Cost:** {} to build, {} a year to run.", inr(b["capex"].as_f64().unwrap_or(0.0)), inr(b["opex"].as_f64().unwrap_or(0.0)));
    let g = &r["green"];
    println!("**Green:** {} trees planted, {} removed, {} affected; {} kWp solar; {} m³ rainwater a year.", g["planted"], g["removed"], g["affected"], g["solar_kwp"], g["rwh_m3"]);
    println!("**Warnings:** {}", r["warnings"]);
    for it in r["items"].as_array().into_iter().flatten() {
        for m in it["warn"].as_array().into_iter().flatten() {
            println!("- {}: {}", it["id"].as_str().unwrap_or(""), m.as_str().unwrap_or(""));
        }
    }
    Ok(())
}
